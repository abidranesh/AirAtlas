"""Generate docs/aqi-standards/*.md from the JSON tables, so code and docs cannot disagree.

    python -m airatlas_aqi.docgen          # write
    pytest                                 # test_docs_are_generated_from_tables fails if stale
"""

from pathlib import Path

from .base import AqiStandard
from .registry import COMMON_SCALES, LOCAL_STANDARD, SECONDARY_STANDARDS, STANDARDS, get_standard

DOCS_DIR = Path(__file__).resolve().parents[3] / "docs" / "aqi-standards"
HEADER = "<!-- Generated by `python -m airatlas_aqi.docgen` from aqi-engine/src/airatlas_aqi/tables/{code}.json. Do not edit by hand. -->\n\n"
POLLUTANT_LABEL = {"pm25": "PM2.5", "pm10": "PM10", "no2": "NO₂", "o3": "O₃", "so2": "SO₂", "co": "CO", "nh3": "NH₃", "pb": "Pb"}
UNIT_LABEL = {"ug/m3": "µg/m³", "mg/m3": "mg/m³"}


def _num(x: float) -> str:
    return f"{x:g}"


def _breakpoint_rows(std: AqiStandard) -> tuple[list[str], list[list[str]]]:
    cats = [c.label for c in std.categories]
    head = ["Pollutant", "Averaging", "Unit", *cats]
    rows = []
    method = std.spec["method"]
    for p, cfg in std.spec["pollutants"].items():
        unit = UNIT_LABEL[cfg["unit"]]
        if method == "continuous":
            bps = cfg["breakpoints"]
            cells = [f"{_num(bps[i])}–{_num(bps[i + 1])}" for i in range(len(bps) - 1)] + [f"> {_num(bps[-1])}"]
            rows.append([POLLUTANT_LABEL[p], cfg["averaging"], unit, *cells])
        elif method == "step":
            ups, cells, lo = cfg["upper"], [], None
            for up in ups:
                if up is None:
                    cells.append(f"> {_num(lo)}")
                elif lo is None:
                    cells.append(f"0–{_num(up)}")
                else:
                    cells.append(f"{_num(lo + 1)}–{_num(up)}" if cfg.get("round") == 0 else f"> {_num(lo)}–{_num(up)}")
                lo = up
            rows.append([POLLUTANT_LABEL[p], cfg["averaging"], unit, *cells])
        else:  # segments: place each segment under the category its index range belongs to
            for avg, acfg in cfg["averagings"].items():
                cells = ["–"] * len(cats)
                for bp_lo, bp_hi, i_lo, _ in acfg["segments"]:
                    cells[std.category_for(i_lo).level - 1] = f"{_num(bp_lo)}–{_num(bp_hi)}"
                rows.append([POLLUTANT_LABEL[p], avg, unit, *cells])
    return head, rows


def _table(head: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    lines += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(lines) + "\n"


def render_standard(std: AqiStandard) -> str:
    s = std.spec
    scale = s["scale"]
    scale_txt = f"index {scale['min']}–{scale['max']}" if scale["type"] == "index" else f"levels {scale['min']}–{scale['max']}"
    out = [HEADER.format(code=std.code), f"# {s['name']}\n\n"]
    out.append(f"Code `{std.code}` · version {s['version']} · scale: {scale_txt} · method: {s['method']}\n\n")
    out.append("## Sources\n\n")
    out += [f"- [{src['title']}]({src['url']}), accessed {src['accessed']}\n" for src in s["sources"]]

    out.append("\n## Categories\n\n")
    head = ["Level", "Category", "Index" if std.is_index_scale else "", "Colour", "Health message"]
    rows = []
    for c in std.categories:
        idx = f"{c.index_range[0]}–{c.index_range[1]}" if c.index_range else ""
        msg = c.health + (f" *Sensitive groups:* {c.health_sensitive}" if c.health_sensitive else "")
        rows.append([str(c.level), c.label, idx, f"`{c.color}`", msg])
    if not std.is_index_scale:
        head.pop(2)
        for r in rows:
            r.pop(2)
    out.append(_table(head, rows))

    out.append("\n## Breakpoints\n\n")
    out.append(_table(*_breakpoint_rows(std)))
    if s["method"] == "continuous":
        out.append(f"\nIndex points at each breakpoint: {', '.join(map(_num, s['index_points']))}.\n")

    if "reference_guidelines" in s:
        out.append("\n### WHO 2021 guideline values (IT1, IT2, IT3, IT4, AQG)\n\n")
        rows = [
            [POLLUTANT_LABEL[p], period, *("–" if v is None else _num(v) for v in vals)]
            for p, periods in s["reference_guidelines"].items()
            for period, vals in periods.items()
        ]
        out.append(_table(["Pollutant", "Averaging", "IT1", "IT2", "IT3", "IT4", "AQG"], rows))

    out.append("\n## Rules\n\n")
    out += [f"- {r}\n" for r in s["rules"]]
    if s.get("notes"):
        out.append("\n## Implementation notes and source discrepancies\n\n")
        out += [f"- {n}\n" for n in s["notes"]]
    return "".join(out)


def render_index() -> str:
    regions: dict[str, list[str]] = {}
    for region, code in LOCAL_STANDARD.items():
        regions.setdefault(code, []).append(f"{region} (default)")
    for region, codes in SECONDARY_STANDARDS.items():
        for code in codes:
            regions.setdefault(code, []).append(region)
    for code in COMMON_SCALES:
        regions.setdefault(code, []).append("all regions (common scale)")

    rows = []
    for code in STANDARDS:
        std = get_standard(code)
        s = std.spec
        scale = s["scale"]
        used = {a for cfg in s["pollutants"].values() for a in ([cfg["averaging"]] if "averaging" in cfg else cfg["averagings"])}
        avgs = [a for a in ("1h", "8h", "8h_max24", "24h") if a in used]
        rows.append([
            f"[{s['short_name']}]({code}.md)",
            ", ".join(regions.get(code, [])),
            f"{scale['min']}–{scale['max']}" if scale["type"] == "index" else f"{len(std.categories)} levels",
            ", ".join(POLLUTANT_LABEL[p] for p in s["pollutants"]),
            ", ".join(avgs),
            {"continuous": "linear (continuous)", "segments": "linear (US-EPA segments)", "step": "banded"}[s["method"]],
        ])
    body = _table(["Standard", "Used for", "Scale", "Pollutants", "Averaging", "Sub-index"], rows)
    return (
        "<!-- Generated by `python -m airatlas_aqi.docgen`. Do not edit by hand. -->\n\n"
        "# AQI standards in AirAtlas\n\n"
        "Every standard is computed from stored raw concentrations at read or ingestion time. Breakpoints live in "
        "JSON tables (`aqi-engine/src/airatlas_aqi/tables/`), and these pages are generated from those tables.\n\n"
        + body
        + "\nWhy the same air gets different labels: India's CPCB 'Satisfactory' band reaches 60 µg/m³ PM2.5 (24 h), "
        "while WHO's 2021 guideline is 15 and the European index calls anything above 15 µg/m³ (hourly) "
        "'Moderate' or worse. Cross-country comparisons therefore always use a common scale.\n"
    )


def render_all() -> dict[Path, str]:
    out = {DOCS_DIR / f"{code}.md": render_standard(get_standard(code)) for code in STANDARDS}
    out[DOCS_DIR / "README.md"] = render_index()
    return out


if __name__ == "__main__":
    DOCS_DIR.mkdir(parents=True, exist_ok=True)
    for path, content in render_all().items():
        path.write_text(content, encoding="utf-8")
        print(f"wrote {path.relative_to(DOCS_DIR.parents[1])}")
